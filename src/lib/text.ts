// Общая типографика/деривация текста — одна логика для сайта И сида,
// чтобы «краткое описание» совпадало при переносе в БД.

/** Первое предложение строки (до . ! ?); если его нет — вся строка. */
export function firstSentence(s: string): string {
  const m = s.match(/^[^.!?]*[.!?]/);
  return m && m[0].length < s.length ? m[0] : s;
}
