// Общая типографика/деривация текста — одна логика для сайта И сида,
// чтобы «краткое описание» совпадало при переносе в БД.

/** Первое предложение строки (до . ! ?); если его нет — вся строка. */
export function firstSentence(s: string): string {
  const m = s.match(/^[^.!?]*[.!?]/);
  return m && m[0].length < s.length ? m[0] : s;
}

/**
 * Экранирование для Telegram parse_mode:"HTML". ЕДИНЫЙ источник — раньше было
 * два побайтово одинаковых дубля (orders.ts esc + bot.ts esc), правка
 * безопасности в одном молча не попадала во второй (аудит-халтура). ОБЯЗАТЕЛЬНО
 * для любых значений из БД/ввода гостя/владельца: < > & иначе ломают entities.
 * & экранируем ПЕРВЫМ, иначе &lt; превратится в &amp;lt;.
 */
export function escapeHtml(s: string | null | undefined): string {
  return (s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/**
 * Короткий отпечаток значения для callback_data (защита от гонки двух админов,
 * аудит M5): кнопка «удалить/править №i» несёт отпечаток значения, каким его
 * видел админ; если к моменту тапа элемент под индексом сменился — отпечаток
 * не совпадёт и бот попросит открыть список заново, вместо правки не той строки.
 * Не криптография — djb2 в base36, 6 символов (callback_data ограничен 64 байтами).
 */
export function stamp(s: string): string {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(36).slice(0, 6);
}
