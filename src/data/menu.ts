/** Цена голыми цифрами — приём fine-dining: «4 900».
 *  Разделитель групп — узкий неразрывный пробел U+202F, чтобы число не
 *  разваливалось и не переносилось (в паре с tabular-nums). */
export function formatNumber(amount: number): string {
  return amount.toLocaleString("ru-RU").replace(/\s/g, " ");
}
