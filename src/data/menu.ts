// - свёрнуто видно только имя · размер · цена; описание и доп.
//   форматы — под тап (поля note / variants);
// - spicy — острая позиция (флаг для будущей метки; пока без значка);
// - провенанс (origin) — только там, где он подтверждён названием
//   (Краб/Камчатка, Креветки/Магадан; у раков провенанса в доке НЕТ);
// - signature (◆) — кураторский набор «героев» дома (краб, микс-улов,
