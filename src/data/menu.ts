/** Адрес, который кодируется в QR на столах. Поменять перед печатью. */
export const MENU_URL = "https://menu.theraki.ru";

export type MenuEntry = {
  name: string;
  /** Короткая редакторская строка под названием. Без неё — просто позиция. */
  note?: string;
  price: number;
  /** Единица подачи: «кг», «100 г», «250 г», «0,5 л», «порция»… */
  unit?: string;
  /** Дополнительные форматы подачи: «500 г — 10 000». */
  variants?: { label: string; price: number }[];
  /** Фирменная позиция — получает тонкую отметку в карте. */
  signature?: boolean;
};

export type Chapter = {
  id: string;
  /** Римский номер главы проставляется по порядку — в данных не хранится. */
  title: string;
  /** Подзаголовок главы — одна строка, спокойная. */
  lede?: string;
  /** Провенанс: откуда продукт. Печатается тонкой mono-строкой. */
  origin?: string;
  entries: MenuEntry[];
  /** Сноска внизу главы: соусы, включённая подача и т.п. */
  footnotes?: string[];
};

// ------------------------------------------------------------
// Раки — центральная глава с собственной версткой:
// матрица цен (размер x приготовление) + рецепты с надбавками.
// ------------------------------------------------------------

export type RakiPreparation = {
  id: string;
  title: string;
  /** Базовая цена за кг (размер M). */
  basePrice: number;
  /** Заголовок списка рецептов: «Рецепты варки» и т.п. */
  recipesLabel: string;
  /** Рецепты; extra — надбавка к цене за кг. */
  recipes: { name: string; extra?: number }[];
};

export type RakiSizeTier = {
  tier: string;
  /** Сколько штук в килограмме. */
  countPerKg: string;
  /** Полная цена за кг по каждому приготовлению, в порядке preparations. */
  prices: number[];
};

